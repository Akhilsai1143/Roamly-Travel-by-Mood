// Normalization helper for multi-word or slug variations
const SLUG_ALIASES = {
  "spiti valley": "spiti",
  "spiti-valley": "spiti",
  "andaman islands": "andaman",
  "andaman-islands": "andaman",
  "rann of kutch": "kutch",
  "rann-of-kutch": "kutch",
  "swiss alps": "switzerland",
  "swiss-alps": "switzerland",
  "cape town": "cape-town",
  "capetown": "cape-town"
};

export function normalizeDestinationKey(destId) {
  if (!destId) return "munnar";
  const raw = String(destId).toLowerCase().trim();
  if (sampleItineraries[raw]) return raw;
  if (SLUG_ALIASES[raw]) return SLUG_ALIASES[raw];
  const slug = raw.replace(/\s+/g, "-");
  if (sampleItineraries[slug]) return slug;
  return "munnar";
}

/**
 * Returns a tailored day-by-day itinerary array of strings for any destination and duration.
 * Guaranteed to match the destination and return authentic stops.
 */
export function getDestinationItinerary(destinationId, daysCount = 3, travelStyle = "") {
  const key = normalizeDestinationKey(destinationId);
  const fullItin = sampleItineraries[key] || sampleItineraries["munnar"];
  const numDays = Math.max(1, Math.min(7, parseInt(daysCount, 10) || 3));
  
  // Slice to the requested number of days
  const selectedDays = fullItin.slice(0, numDays);
  
  return selectedDays.map((s) => `Day ${s.day} — ${s.title}: ${s.activity}`);
}

/**
 * Returns structured day objects { day, title, activity } for detailed UI rendering.
 */
export function getDestinationStructuredItinerary(destinationId, daysCount = 3) {
  const key = normalizeDestinationKey(destinationId);
  const fullItin = sampleItineraries[key] || sampleItineraries["munnar"];
  const numDays = Math.max(1, Math.min(7, parseInt(daysCount, 10) || 3));
  return fullItin.slice(0, numDays);
}

