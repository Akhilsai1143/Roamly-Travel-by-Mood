/**
 * Returns 12 authentic, distinct gallery photos for any destination.
 */
export function getDestinationGallery(dest) {
  if (!dest) return CATEGORY_FALLBACKS.Mountains;
  const idKey = String(dest.id || "").toLowerCase().trim();
  const nameKey = String(dest.name || "").toLowerCase().trim();
  if (DESTINATION_GALLERIES[idKey]) return DESTINATION_GALLERIES[idKey];
  if (DESTINATION_GALLERIES[nameKey]) return DESTINATION_GALLERIES[nameKey];
  if (Array.isArray(dest.gallery) && dest.gallery.length >= 10) return dest.gallery;
  const catKey = dest.category || "Mountains";
  return CATEGORY_FALLBACKS[catKey] || CATEGORY_FALLBACKS.Mountains;
}

/**
 * Returns landmark names/captions matching the destination gallery photos.
 */
export function getDestinationLandmarks(dest) {
  if (!dest) return [];
  const idKey = String(dest.id || "").toLowerCase().trim();
  const nameKey = String(dest.name || "").toLowerCase().trim();
  if (DESTINATION_LANDMARKS[idKey]) return DESTINATION_LANDMARKS[idKey];
  if (DESTINATION_LANDMARKS[nameKey]) return DESTINATION_LANDMARKS[nameKey];
  return [];
}
